    #[test]
    fn https_providers_are_extracted_and_rewritten_to_hashed_relative_files() {
        let input = r#"
proxy-providers:
  paid-nodes:
    type: http
    url: https://provider.example/sub?token=sensitive
    path: C:/attacker/chosen.yaml
    interval: 60
rule-providers:
  private-rules:
    type: http
    url: https://rules.example/list.txt#ignored
    path: ../../escape.txt
    behavior: classical
    format: text
rules: ["RULE-SET,private-rules,DIRECT", "MATCH,paid-nodes"]
"#;

        let result = sanitized(input, Transport::System, DnsMode::FakeIp);
        assert_eq!(result.provider_downloads.len(), 2);
        assert_eq!(result.provider_downloads[0].kind, ProviderKind::Proxy);
        assert_eq!(
            result.provider_downloads[0].url,
            "https://provider.example/sub?token=sensitive"
        );
        assert_eq!(result.provider_downloads[1].kind, ProviderKind::Rule);
        assert_eq!(
            result.provider_downloads[1].url,
            "https://rules.example/list.txt"
        );

        let output = parse_output(&result);
        let proxy_provider = field(field(&output, "proxy-providers"), "paid-nodes");
        let rule_provider = field(field(&output, "rule-providers"), "private-rules");
        for provider in [proxy_provider, rule_provider] {
            assert_eq!(field(provider, "type").as_str(), Some("file"));
            assert!(
                field(provider, "path")
                    .as_str()
                    .unwrap()
                    .starts_with("providers/")
            );
            assert!(
                !provider
                    .as_mapping()
                    .unwrap()
                    .contains_key(Value::String("url".into()))
            );
        }
        assert_eq!(field(rule_provider, "behavior").as_str(), Some("classical"));
        assert_eq!(field(rule_provider, "format").as_str(), Some("text"));
        assert!(
            field(rule_provider, "path")
                .as_str()
                .unwrap()
                .ends_with(".txt")
        );
        assert!(!result.effective_yaml.contains("sensitive"));
        assert!(!result.effective_yaml.contains("C:/attacker"));
        assert!(!result.effective_yaml.contains(".."));
    }

