    fn sanitized(yaml: &str, transport: Transport, dns_mode: DnsMode) -> SanitizedProfile {
        sanitize_profile(yaml.as_bytes(), &options(transport, dns_mode)).unwrap()
    }

    fn parse_output(result: &SanitizedProfile) -> Value {
        serde_yaml::from_str(&result.effective_yaml).unwrap()
    }

    fn field<'a>(value: &'a Value, key: &str) -> &'a Value {
        get(value.as_mapping().unwrap(), key).unwrap()
    }

